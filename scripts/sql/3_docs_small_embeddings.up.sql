-- Migration: fit the documents table to BAAI/bge-small-en-v1.5
-- Version: 3
-- The old vectors cannot be searched with the new model, so the table is emptied;
-- call POST /index/rebuild on the RAG server afterwards.

TRUNCATE TABLE "public"."documents";

-- A few thousand rows are scanned exactly; the ivfflat index only lowered recall.
DROP INDEX IF EXISTS "public"."documents_embedding_idx";

ALTER TABLE "public"."documents" ALTER COLUMN "embedding" TYPE vector(384);
ALTER TABLE "public"."documents" ADD COLUMN IF NOT EXISTS "content_hash" TEXT;

COMMENT ON COLUMN "public"."documents"."embedding" IS 'Vector embedding (384-dim) generated by BAAI/bge-small-en-v1.5';
COMMENT ON COLUMN "public"."documents"."content_hash" IS 'MD5 of the source file, used to index only changed documents';

INSERT INTO "public"."schema_migrations" (version, description)
VALUES ('3', 'Switch documents to 384-dimension embeddings and add content_hash')
ON CONFLICT (version) DO NOTHING;
